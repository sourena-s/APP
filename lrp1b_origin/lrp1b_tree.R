suppressPackageStartupMessages(library(ape))
tr <- read.tree("t2.contree"); tr <- ladderize(root(tr, "Fly_LRP1|A0A0B4KFD1", resolve.root = TRUE), FALSE)
lab <- sub("\\|.*", "", tr$tip.label); lab <- gsub("_", " ", lab)
col <- ifelse(grepl("LRP1B|lrp1b", lab), "#B2182B", ifelse(grepl("like|Fly", lab), "grey35", "#2166AC"))
tr$tip.label <- lab
png("fig10_LRP1_LRP1B_gene_tree.png", width = 2600, height = 2000, res = 300)
par(mar = c(3, 1, 3.5, 1))
plot(tr, tip.color = col, cex = .8, label.offset = .02, edge.width = 1.6, x.lim = 2.6)
dup <- getMRCA(tr, tr$tip.label[grepl("Human LRP1$|Human LRP1B", tr$tip.label)])
nodelabels(node = dup, pch = 23, bg = "#F2B701", cex = 2.2)
nodelabels("76", node = dup, frame = "none", cex = .6, adj = c(-.6, -.9), col = "grey30")
bs <- suppressWarnings(as.numeric(tr$node.label)); nodelabels(ifelse(!is.na(bs) & bs >= 70 & seq_along(bs) + Ntip(tr) != dup, bs, ""), frame = "none", cex = .55, adj = c(1.15, -.45), col = "grey30")
#(tr, tr$tip.label[grepl("Human LRP1$|Human LRP1B", tr$tip.label)])
add.scale.bar(x = 1.9, y = 3, cex = .7)
title(main = "LRP1 / LRP1B gene tree (C-terminal ~500 aa; IQ-TREE JTTDCMut+G4, 1000 UFBoot)", cex.main = .85)
legend("topleft", inset = c(0, .02), c("LRP1 orthologues", "LRP1B orthologues", "pre-duplication (single gene)", "duplication LRP1 -> LRP1 + LRP1B"),
       text.col = c("#2166AC", "#B2182B", "grey35", "black"), pch = c(NA, NA, NA, 23), pt.bg = "#F2B701", bty = "n", cex = .7)
mtext("Duplication after the lamprey (cyclostome) split, before the shark split: ~600-460 Mya, early jawed vertebrates", side = 1, line = 1.5, cex = .7)
dev.off()
